// Построчная сверка двух версий системного промта — своей и встроенной.
//
// ЗАЧЕМ. Правила в панели правятся кусками и годами, а встроенный текст меняется вместе с кодом.
// Через несколько правок ответить на вопрос «что я вообще поменял» можно было только чтением двух
// простыней рядом, и на живом тексте это не работает: 48 строк против 51, отличий шесть, и часть из
// них — переписанная формулировка, а не удаление. Сверка показывает ровно это и ровно там, где
// текст правят.
//
// БАЗА — ВСТРОЕННЫЙ ТЕКСТ, а не наоборот. Зелёное — то, что дописал администратор; красное — то,
// что он из встроенных правил убрал. Направление выбрано так, потому что вопрос всегда задаётся об
// одном: чего в моём тексте нет из того, что код считает нужным.
//
// LCS, А НЕ СРАВНЕНИЕ МНОЖЕСТВ. Множество строк ответило бы «эта строка исчезла, эта появилась», но
// потеряло бы порядок и соседство: переписанная строка должна показываться как удаление и
// добавление РЯДОМ, иначе её не опознать как одну правку. Матрица здесь размером в полсотни на
// полсотни, то есть считается быстрее, чем страница рендерится.
//
// СВЕРЯЕТСЯ СОХРАНЁННЫЙ ТЕКСТ, а не то, что сейчас набрано в поле. Живая сверка по мере набора
// потребовала бы этот же алгоритм на клиенте — третью копию того, чему нельзя разъезжаться, — а
// отвечает она на другой вопрос: «что я сейчас печатаю», тогда как спрашивают «что у меня
// сохранено».

// Сравнение идёт по обрезанным строкам, а показывается исходная. Хвостовой пробел — это не правка
// правила, и подсвечивать его как правку значит топить настоящие отличия в шуме.
function key(line) {
  return String(line).trim();
}

// Пустой текст - это НОЛЬ строк, а не одна пустая. Разница не теоретическая: пустой systemPrompt
// это обычное состояние «работают встроенные правила», и разбор его как одной пустой строки
// показывал бы в сверке добавленную пустую строку, которой никто не добавлял.
function splitLines(text) {
  const normalized = String(text ?? "").replace(/\r\n?/g, "\n");
  return normalized.trim() ? normalized.split("\n") : [];
}

/**
 * Строит построчную сверку `builtin` -> `custom`.
 *
 * Возвращает { rows, added, removed, same, identical }, где row — это
 * { type: "same" | "add" | "del", text }. Порядок строк пригоден для показа как есть:
 * неизменные идут на своих местах, удаление и добавление одной переписанной строки — рядом.
 */
function diffLines(builtin, custom) {
  const a = splitLines(builtin);
  const b = splitLines(custom);
  const ak = a.map(key);
  const bk = b.map(key);

  // Классическая таблица длин наибольшей общей подпоследовательности. lcs[i][j] — длина для
  // хвостов a[i..] и b[j..]; так восстановление идёт вперёд и строки выходят в исходном порядке.
  const lcs = Array.from({ length: a.length + 1 }, () => new Array(b.length + 1).fill(0));
  for (let i = a.length - 1; i >= 0; i -= 1) {
    for (let j = b.length - 1; j >= 0; j -= 1) {
      lcs[i][j] = ak[i] === bk[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
    }
  }

  const rows = [];
  let i = 0;
  let j = 0;
  while (i < a.length && j < b.length) {
    if (ak[i] === bk[j]) {
      rows.push({ type: "same", text: b[j] });
      i += 1;
      j += 1;
    } else if (lcs[i + 1][j] >= lcs[i][j + 1]) {
      // Удаление вперёд добавления: переписанная строка читается как «было / стало», а не наоборот.
      rows.push({ type: "del", text: a[i] });
      i += 1;
    } else {
      rows.push({ type: "add", text: b[j] });
      j += 1;
    }
  }
  while (i < a.length) {
    rows.push({ type: "del", text: a[i] });
    i += 1;
  }
  while (j < b.length) {
    rows.push({ type: "add", text: b[j] });
    j += 1;
  }

  const added = rows.filter((r) => r.type === "add").length;
  const removed = rows.filter((r) => r.type === "del").length;
  return {
    rows,
    added,
    removed,
    same: rows.length - added - removed,
    identical: added === 0 && removed === 0,
  };
}

module.exports = { diffLines };
